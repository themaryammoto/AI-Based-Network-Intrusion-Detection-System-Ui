// Helper to generate realistic simulated live traffic flow rows
const BENIGN_IPS = ['192.168.10.5', '192.168.10.9', '192.168.10.14', '192.168.10.16', '192.168.10.19', '192.168.10.25'];
const DEST_IPS = ['192.168.10.50', '192.168.10.3', '192.168.10.51', '172.217.10.46', '104.16.207.165', '52.84.145.9'];
const ATTACK_SOURCES = ['172.16.0.1', '172.16.0.12', '205.174.165.73', '192.168.10.8'];
const ATTACK_LABELS = ['DoS Hulk', 'PortScan', 'DDoS', 'SSH-Patator', 'Web Attack XSS', 'Bot'];
const PROTOCOLS: Array<'TCP' | 'UDP' | 'ICMP'> = ['TCP', 'TCP', 'TCP', 'UDP', 'UDP', 'ICMP'];

let flowCounter = 9000;

export function generateLiveFlowRow(attackProbability = 0.22): LiveFlowRow {
  flowCounter += 1;
  const isAttack = Math.random() < attackProbability;
  const now = new Date();
  const timestamp = now.toTimeString().slice(0, 8);
  const protocol = isAttack ? (Math.random() < 0.86 ? 'TCP' : 'UDP') : PROTOCOLS[Math.floor(Math.random() * PROTOCOLS.length)];
  const sourceIp = isAttack
    ? ATTACK_SOURCES[Math.floor(Math.random() * ATTACK_SOURCES.length)]
    : BENIGN_IPS[Math.floor(Math.random() * BENIGN_IPS.length)];
  const destinationIp = isAttack
    ? '192.168.10.50'
    : DEST_IPS[Math.floor(Math.random() * DEST_IPS.length)];

  const attackLabel = isAttack ? ATTACK_LABELS[Math.floor(Math.random() * ATTACK_LABELS.length)] : 'BENIGN';

  const packets = isAttack ? Math.floor(180 + Math.random() * 1400) : Math.floor(4 + Math.random() * 68);
  const bytes = isAttack ? packets * Math.floor(64 + Math.random() * 340) : packets * Math.floor(80 + Math.random() * 620);
  const flowDurationMs = isAttack ? Math.floor(12 + Math.random() * 3800) : Math.floor(45 + Math.random() * 1850);
  const confidence = isAttack
    ? Number((94.2 + Math.random() * 5.6).toFixed(1))
    : Number((96.1 + Math.random() * 3.8).toFixed(1));

  return {
    id: `FLW-${flowCounter}`,
    timestamp,
    sourceIp,
    destinationIp,
    protocol,
    flowDurationMs,
    packets,
    bytes,
    prediction: isAttack ? 'ATTACK' : 'BENIGN',
    attackLabel,
    confidence,
  };
}

